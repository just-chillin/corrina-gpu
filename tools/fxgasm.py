#!/usr/bin/env python3
"""Assembler for the FXG-1 shader ISA.

  fxgasm.py NAME=file.s [NAME=file.s ...] -o shaders.h

Syntax: one instruction per line, ';' comments, 'label:' lines.
Pseudo-ops: LDC rd, <32-bit int>   LDF rd, <float>  (both expand to LDI+LUI)
"""
import sys

OPS = {n: i for i, n in enumerate(
    "HALT LDI LUI MOV ADD SUB MUL MULF AND OR XOR SHL SHR SAR SLT MIN MAX "
    "IN OUT UNI TEX BZ BNZ JMP RCP KILL ADDI SHLI SHRI SARI".split())}

RRR = {"ADD", "SUB", "MUL", "MULF", "AND", "OR", "XOR", "SHL", "SHR", "SAR",
       "SLT", "MIN", "MAX", "TEX"}
RRI = {"ADDI", "SHLI", "SHRI", "SARI"}


def reg(tok):
    if not tok.lower().startswith("r"):
        raise ValueError(f"expected register, got {tok!r}")
    n = int(tok[1:])
    if not 0 <= n <= 15:
        raise ValueError(f"bad register {tok!r}")
    return n


def enc(op, rd=0, ra=0, rb=0, imm=None):
    w = (OPS[op] << 24) | (rd << 20) | (ra << 16)
    return w | ((imm & 0xFFFF) if imm is not None else (rb << 12))


def assemble(path):
    lines = []
    for ln, raw in enumerate(open(path), 1):
        text = raw.split(";")[0].strip()
        if text:
            lines.append((ln, text))

    # Pass 1: label addresses (LDC/LDF occupy two words).
    labels, pc = {}, 0
    for ln, text in lines:
        if text.endswith(":"):
            labels[text[:-1]] = pc
        else:
            pc += 2 if text.split()[0].upper() in ("LDC", "LDF") else 1
    if pc > 256:
        sys.exit(f"{path}: program is {pc} words, limit is 256")

    out = []
    for ln, text in lines:
        if text.endswith(":"):
            continue
        op, _, rest = text.partition(" ")
        op = op.upper()
        a = [t.strip() for t in rest.split(",")] if rest.strip() else []
        try:
            if op in ("LDC", "LDF"):
                v = int(round(float(a[1]) * 65536)) if op == "LDF" else int(a[1], 0)
                v &= 0xFFFFFFFF
                out += [enc("LDI", rd=reg(a[0]), imm=v & 0xFFFF),
                        enc("LUI", rd=reg(a[0]), imm=v >> 16)]
            elif op == "HALT":
                out.append(enc(op))
            elif op == "LDI":
                out.append(enc(op, rd=reg(a[0]), imm=int(a[1], 0)))
            elif op in ("MOV", "RCP"):
                out.append(enc(op, rd=reg(a[0]), ra=reg(a[1])))
            elif op in RRR:
                out.append(enc(op, rd=reg(a[0]), ra=reg(a[1]), rb=reg(a[2])))
            elif op in RRI:
                out.append(enc(op, rd=reg(a[0]), ra=reg(a[1]), imm=int(a[2], 0)))
            elif op in ("IN", "UNI"):
                out.append(enc(op, rd=reg(a[0]), imm=int(a[1], 0)))
            elif op == "OUT":
                out.append(enc(op, ra=reg(a[1]), imm=int(a[0], 0)))
            elif op in ("BZ", "BNZ"):
                out.append(enc(op, ra=reg(a[0]), imm=labels[a[1]]))
            elif op == "JMP":
                out.append(enc(op, imm=labels[a[0]]))
            elif op == "KILL":
                out.append(enc(op, ra=reg(a[0])))
            else:
                raise ValueError(f"unknown instruction {op}")
        except (IndexError, KeyError, ValueError) as e:
            sys.exit(f"{path}:{ln}: {e}: {text}")
    return out


def main():
    args = sys.argv[1:]
    dst = args[args.index("-o") + 1]
    srcs = [a for a in args[:args.index("-o")]]
    with open(dst, "w") as f:
        f.write("/* Generated by tools/fxgasm.py. Do not edit. */\n#include <stdint.h>\n")
        for s in srcs:
            name, path = s.split("=", 1)
            words = assemble(path)
            f.write(f"\nstatic const uint32_t {name}[{len(words)}] = {{\n")
            for i in range(0, len(words), 6):
                f.write("    " + ", ".join(f"0x{w:08x}" for w in words[i:i + 6]) + ",\n")
            f.write("};\n")


if __name__ == "__main__":
    main()
